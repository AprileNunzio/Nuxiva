fn strings(items: &[&str]) -> Vec<String> {
    items.iter().map(|item| (*item).to_owned()).collect()
}

struct Spec<'a> {
    id: &'a str,
    vendor: &'a str,
    kind: Kind,
    devices: &'a [&'a str],
    modules: &'a [&'a str],
    drm: &'a [&'a str],
    accel: &'a [&'a str],
    usb: &'a [[u16; 2]],
    pci: &'a [u16],
    compatible: &'a [&'a str],
    runtimes: &'a [&'a str],
    tasks: &'a [Task],
    priority: u8,
    llm_min_ram_mb: u32,
}

impl Spec<'_> {
    fn build(&self) -> Descriptor {
        Descriptor {
            id: self.id.to_owned(),
            vendor: self.vendor.to_owned(),
            kind: self.kind,
            devices: strings(self.devices),
            modules: strings(self.modules),
            drm_drivers: strings(self.drm),
            accel_drivers: strings(self.accel),
            usb: self.usb.to_vec(),
            pci_vendors: self.pci.to_vec(),
            compatible: strings(self.compatible),
            runtimes: strings(self.runtimes),
            tasks: self.tasks.to_vec(),
            priority: self.priority,
            llm_min_ram_mb: self.llm_min_ram_mb,
        }
    }
}

