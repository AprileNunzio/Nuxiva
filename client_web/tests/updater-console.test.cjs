const {readFileSync}=require('node:fs');
const {resolve}=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ts=require('typescript');
const moduleContext={exports:{}};
const code=ts.transpileModule(readFileSync(resolve(__dirname,'../src/core_apps/updater/consoleFormat.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
vm.runInNewContext(code,{exports:moduleContext.exports,module:moduleContext,Date,Object,String,Math,Number});
const {formatLine,stageDuration,clockTime}=moduleContext.exports;
const line=formatLine({t:1700000000,level:'ok',code:'stage_done',stage:'integrity',args:{files:5525,algorithm:'sha1',empty:'',none:null}},3);
assert.equal(line.messageKey,'log_stage_done');
assert.equal(line.detail,'files=5525 algorithm=sha1');
assert.deepEqual({...line.params},{files:'5525',algorithm:'sha1'});
assert.equal(line.key,'1700000000-3');
assert.match(line.time,/^\d{2}:\d{2}:\d{2}$/);
assert.equal(clockTime(Number.NaN),'--:--:--');
assert.equal(stageDuration(null,null,10),null);
assert.equal(stageDuration(10,12.34,99),'2.3s');
assert.equal(stageDuration(0,null,125),'2m05s');
assert.equal(stageDuration(10,5,99),'0.0s');
console.log('Updater console: line formatting, sanitised params and stage durations passed.');
