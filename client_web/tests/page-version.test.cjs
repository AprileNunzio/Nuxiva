const {readFileSync}=require('node:fs');
const {resolve}=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ts=require('typescript');
const moduleContext={exports:{}};
const code=ts.transpileModule(readFileSync(resolve(__dirname,'../src/shared/updates/pageVersion.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
vm.runInNewContext(code,{exports:moduleContext.exports,module:moduleContext,URL});
const {entryOf,isNewer,appRoot,bundleDir}=moduleContext.exports;
const page=(name)=>`<!doctype html><html><head><script type="module" crossorigin src="/assets/${name}.js"></script><link rel="stylesheet" href="/assets/x.css"></head><body></body></html>`;
assert.equal(entryOf(page('index-abc')),'/assets/index-abc.js');
assert.equal(entryOf('<script src="/assets/i-1.js" type="module"></script>'),'/assets/i-1.js');
assert.equal(entryOf('<html>login</html>'),null);
assert.equal(isNewer('/assets/index-abc.js','/assets/index-abc.js'),false,'same build');
assert.equal(isNewer('/assets/index-abc.js','/assets/index-def.js'),true,'new build');
assert.equal(isNewer(null,'/assets/index-def.js'),false,'unknown loaded entry never reloads');
assert.equal(isNewer('/assets/index-abc.js',null),false,'unparseable response never reloads');
const display='<html><head><script type="module" src="/static/shared/i18n/runtime.js?v=9"></script><script src="/static/display/perf.js"></script></head></html>';
assert.equal(entryOf(display,'/assets/'),null,'page 80 shell is never mistaken for the 8080 bundle');
assert.equal(isNewer('/assets/index-abc.js','/static/shared/i18n/runtime.js'),false,'foreign module never triggers a reload');
assert.equal(entryOf('<script type="module" src="/static/x.js"></script><script type="module" src="/assets/index-n.js?v=2"></script>','/assets/'),'/assets/index-n.js');
assert.equal(isNewer('/assets/index-abc.js','/assets/index-def.js?v=3'),true,'query string ignored');
assert.equal(appRoot('/admin'),'/admin/');
assert.equal(appRoot('/admin/apps/people'),'/admin/');
assert.equal(appRoot('/administrator'),'/');
assert.equal(appRoot('/apps/people'),'/');
assert.equal(bundleDir('/assets/index-abc.js'),'/assets/');
assert.equal(bundleDir(null),null);
const guardCtx={exports:{}};
const guardCode=ts.transpileModule(readFileSync(resolve(__dirname,'../src/shared/updates/reloadGuard.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
vm.runInNewContext(guardCode,{exports:guardCtx.exports,module:guardCtx,JSON,Number,Math,console});
const g=guardCtx.exports;
const t0=1_000_000;
let rec=null;
assert.equal(g.canAutoReload(rec,'/assets/a.js',t0),true,'first attempt allowed');
rec=g.nextRecord(rec,'/assets/a.js',t0);
assert.equal(g.canAutoReload(rec,'/assets/a.js',t0+1000),true,'second attempt allowed');
rec=g.nextRecord(rec,'/assets/a.js',t0+1000);
assert.equal(rec.attempts,2);
assert.equal(g.canAutoReload(rec,'/assets/a.js',t0+2000),false,'loop stopped after max attempts');
assert.equal(g.canAutoReload(rec,'/assets/b.js',t0+2000),true,'a different build resets the guard');
assert.equal(g.canAutoReload(rec,'/assets/a.js',rec.at+g.WINDOW_MS),true,'guard expires after the window');
assert.equal(g.nextRecord(rec,'/assets/a.js',rec.at+g.WINDOW_MS).attempts,1);
assert.equal(g.settled(rec,'/assets/a.js'),true);
assert.equal(g.settled(rec,'/assets/old.js'),false);
assert.deepEqual(g.parseRecord(JSON.stringify(rec)),rec);
assert.equal(g.parseRecord('{bad'),null);
assert.equal(g.parseRecord(JSON.stringify({target:'javascript:alert(1)',attempts:1,at:1})),null);
assert.equal(g.parseRecord(JSON.stringify({target:'/assets/a.js',attempts:-1,at:1})),null);
assert.equal(g.parseRecord('x'.repeat(5000)),null);
assert.equal(g.pollDelay(0),g.BASE_POLL_MS);
assert.equal(g.pollDelay(1),g.BASE_POLL_MS*2);
assert.equal(g.pollDelay(50),g.MAX_POLL_MS,'backoff is capped');
console.log('Page version: entry detection, admin mount, anti-loop guard and backoff passed.');
