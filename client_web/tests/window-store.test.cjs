const { readFileSync } = require('node:fs');
const { resolve } = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const storage = new Map();
const storageAPI = { getItem: key => storage.get(key), setItem: (key, value) => storage.set(key, value) };
let id = 0;
const moduleContext = { exports: {} };
const apps = [{ id: 'people' }, { id: 'node_apps/audio' }];
const context = {
  exports: moduleContext.exports, module: moduleContext,
  require: name => name === 'react' ? { useSyncExternalStore: (_, read) => read() } : { resolveApp: id => apps.find(a => a.id === id) },
  localStorage: storageAPI, crypto: { randomUUID: () => `window-${++id}` }, window: {},
};
const source = readFileSync(resolve(__dirname, '../src/app_shell/window_manager/WindowStore.ts'), 'utf8');
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, context);
const { windowStore: store, useWindowStore: read } = moduleContext.exports;
store.activateWorkspace('alice');
const first = store.openWindow({ appId: 'people', initialPayload: { secret: 'not-persisted' } });
assert.equal(store.openWindow({ appId: 'people', initialPayload: { filter: '123' } }), first);
assert.equal(read().length, 1);
assert.equal(read()[0].initialPayload.filter, '123');
const audioA = store.openWindow({ appId: 'node_apps/audio', targetNodeId: 'pc-a' });
const audioB = store.openWindow({ appId: 'node_apps/audio', targetNodeId: 'pc-b' });
assert.notEqual(audioA, audioB);
store.update(audioA, { windowMode:'snapped-left', minimized: true, x: 10, y: 12 });
store.focus(audioA);
assert.equal(read().find(w => w.id === audioA).minimized, false);
assert.equal(read().find(w => w.id === audioB).windowMode, 'maximized');
assert.ok(!storage.get('nuxiva.workspace.v1:alice').includes('initialPayload'));
store.activateWorkspace('bob');
assert.equal(read().length, 0);
store.openWindow({ appId: 'people' });
store.activateWorkspace('alice');
assert.equal(read().length, 3);
assert.equal(read().find(w => w.id === audioA).windowMode, 'snapped-left');
assert.equal(read().find(w => w.id === audioA).x, 10);
assert.throws(() => store.openWindow({ appId: '../unknown' }));
assert.throws(() => store.openWindow({ appId: 'people', windowMode: 'bad' }));
store.close(first);
assert.equal(read().length, 2);
store.releaseWorkspace();
assert.equal(read().length, 0);
storage.set('nuxiva.workspace.v1:corrupt', '[{"id":"bad","appId":"people","x":null}]');
store.activateWorkspace('corrupt');
assert.equal(read().length, 0);
console.log('Window store: identity, multi-instance, snap, persistence, account isolation and invalid state passed.');
context.crypto = { getRandomValues: bytes => { bytes.fill(++id); return bytes; } };
assert.ok(store.openWindow({ appId: 'people' }));
console.log('HTTP LAN without crypto.randomUUID: passed.');
context.document={documentElement:{},querySelector:()=>({getBoundingClientRect:()=>({width:7680,height:4320})})};
context.getComputedStyle=()=>({fontSize:'18px'});
store.activateWorkspace('8k');
store.openWindow({appId:'people'});
assert.ok(read()[0].width<20 && read()[0].height<25,'8K uses space for multiple windows rather than oversized chrome');
context.document.querySelector=()=>({getBoundingClientRect:()=>({width:320,height:700})});
store.activateWorkspace('mobile');store.openWindow({appId:'people'});
assert.equal(read()[0].width,96,'small screens use nearly the full workspace');
console.log('Compact 8K window defaults and narrow-screen workspace sizing passed.');

store.activateWorkspace('preferences');
const preferred=store.openWindow({appId:'people'});
assert.equal(read()[0].windowMode,'maximized');
store.update(preferred,{windowMode:'floating',width:42,height:60,x:5,y:8});
store.close(preferred);
store.releaseWorkspace();store.activateWorkspace('preferences');
store.openWindow({appId:'people'});
assert.equal(read()[0].windowMode,'floating');assert.equal(read()[0].width,42);
store.openWindow({appId:'people'});assert.equal(read()[0].windowMode,'floating');
store.activateWorkspace('different-user');store.openWindow({appId:'people'});
assert.equal(read()[0].windowMode,'maximized');
console.log('Per-user app layout persists after close and logout; fresh accounts maximize by default.');
