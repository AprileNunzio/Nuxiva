  function applyLanguage(lang) {
    const table = DICTIONARY[lang] || DICTIONARY.it;
    Object.keys(table).forEach((id) => {
      const el = document.getElementById(id);
      if (el) {
        if (el.tagName === "INPUT") {
          el.placeholder = table[id];
        } else {
          el.textContent = table[id];
        }
      }
    });
    document.documentElement.lang = lang;
  }

  function getStepText(lang, current, total) {
    const table = DICTIONARY[lang] || DICTIONARY.it;
    return `${table["step-prefix"]} ${current} ${table["step-of"]} ${total}`;
  }

  window.SetupI18n = {
    applyLanguage,
    getStepText,
    dictionary: DICTIONARY
  };
